const GENERIC: [Alt, Alt] = [['бюджетный аналог', 0.8], ['премиум-аналог', 1.45]];

const ECO = ' — эконом', PREM = ' — премиум';
const r2 = (v: number) => Math.round(v * 100) / 100;

/** Разбор названия: исходная позиция и класс, на который она переключена */
function parse(name: string): { base: string; tier: Tier } {
  const i = name.lastIndexOf(ECO), j = name.lastIndexOf(PREM);
  if (i > 0 && i >= j) return { base: name.slice(0, i), tier: 'eco' };
  if (j > 0) return { base: name.slice(0, j), tier: 'prem' };
  return { base: name, tier: 'std' };
}

/** Варианты материала для строки сметы (пустой список — если нет названия или цены) */
export function materialVariants(name: string, price: number): Variant[] {
  const nm = String(name || '').trim();
  if (!nm || !(price > 0)) return [];
  const { base, tier } = parse(nm);
  const [eco, prem] = RULES.find(([re]) => re.test(base))?.slice(1) as [Alt, Alt] || GENERIC;
  const std = tier === 'eco' ? price / eco[1] : tier === 'prem' ? price / prem[1] : price;
  return [
    { tier: 'eco', label: TIER_LABEL.eco, name: `${base}${ECO}: ${eco[0]}`, price: r2(std * eco[1]) },
    { tier: 'std', label: TIER_LABEL.std, name: base, price: r2(std) },
    { tier: 'prem', label: TIER_LABEL.prem, name: `${base}${PREM}: ${prem[0]}`, price: r2(std * prem[1]) },
  ];
}

/** Какой вариант сейчас выбран у строки */
export const currentTier = (name: string): Tier => parse(String(name || '').trim()).tier;

/** Переключить строку на вариант: новое название и цена */
export function pickVariant(name: string, price: number, tier: Tier): { name: string; price: number } {
  const v = materialVariants(name, price).find((x) => x.tier === tier);
  return v ? { name: v.name, price: v.price } : { name, price };
}
