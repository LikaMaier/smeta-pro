const INSIDE = /плитк|штукатур|шпакл|покраск|обо(и|ев)|ламинат|линолеум|паркет|стяжк|гкл|гипсокартон|перегородк|санузел|электр|розетк|сантех/i;

const STARTER = new Map(STARTER_PRICES.map((p) => [p.name, p]));

/** Подсказки «часто забывают» для текущих строк сметы (не больше max) */
export function forgottenFor(lines: ForgotLine[], max = 8): Forgot[] {
  const named = lines.filter((l) => l.name?.trim());
  if (!named.length) return [];
  const text = named.map((l) => l.name).join('\n');
  const have = (re: RegExp) => named.some((l) => re.test(l.name));
  const out: Forgot[] = [];
  const add = (name: string, why: string, category: string | null) => {
    const s = STARTER.get(name);
    if (!s || out.some((x) => x.name === name)) return;
    out.push({ name, unit: s.unit, price: s.price, why, category, starterCategory: s.category });
  };
  for (const [trigger, sugs, why] of R) {
    const src = named.find((l) => trigger.test(l.name));
    if (!src) continue;
    for (const [name, already] of sugs) if (!have(already) && !have(new RegExp(name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'i'))) add(name, why, src.category || null);
  }
  if (named.length >= 3) {
    if (!have(/вывоз|мусор|контейнер/i)) add('Вывоз строительного мусора (контейнер 8 м³)', 'в любой смете', null);
    if (!have(/доставк/i)) add('Доставка материалов по городу', 'в любой смете', null);
    if (INSIDE.test(text)) {
      if (!have(/подъ[её]м|занос/i)) add('Подъём материалов на этаж', 'для квартиры', null);
      if (!have(/уборк/i)) add('Уборка после ремонта', 'для квартиры', null);
    }
  }
  return out.slice(0, max);
}

