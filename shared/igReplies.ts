import { PRICES } from './plans';
/** Instagram: готовые ответы на частые комментарии (остальные пересылаются владелице в бот) */
const BOT = '@CMETA_Pro_bot';
/** Выбор варианта по тексту — чтобы ответы не были одинаковыми, но и не случайными */
const pick = (seed: string, v: string[]) => v[[...seed].reduce((a, c) => (a * 31 + c.charCodeAt(0)) >>> 0, 7) % v.length];

/** Спам, ссылки, «взаимные подписки» — не отвечаем */
export function isSpam(text: string) {
  const t = text.toLowerCase();
  return /(https?:\/\/|www\.|\.ru\b|\.com\b|t\.me\/|взаимн|подпишись на|пиши в (лс|директ)|заработ|крипт|ставк|казино|продвижени|раскрутк)/.test(t);
}

/** Жалоба или негатив — общий ответ не годится, только владелица */
export function needsHuman(text: string) {
  return /(не работ|ошибк|баг|глюч|развод|обман|верните|деньги спис|плох|ужас|отстой|фигн|бред|не могу|не получа|не открыва|зависа|вылета)/.test(text.toLowerCase());
}

/** Готовые ответы на частые вопросы; null — переслать администратору */
export function autoReply(text: string): string | null {
  const t = text.toLowerCase().replace(/ё/g, 'е');
  if (isSpam(t)) return null;
  // только эмодзи / знаки — благодарим
  if (!/[a-zа-я0-9]/i.test(t)) return pick(t, ['Спасибо! 🙌', '🙌🔥', 'Спасибо, что смотрите! 👷']);
  if (/^[\s!.)]*((круто|класс|классно|огонь|топ|супер|кайф|ахах[а-я]*|хах[а-я]*|лол|ору|жиза|база|четко|красиво|прикольно|молодц[а-я]*|спасибо|благодарю)[\s!.)]*)+$/u.test(t.replace(/[^\p{L}\s!.)]/gu, '')))
    return pick(t, ['Спасибо! 🙌', 'Рады, что зашло! 🔥', 'Спасибо! Сметы — в ' + BOT + ' 👷', 'Жиза же 😅 Спасибо!']);
  if (/(сколько|цен[аы] (на )?(прил|бот|подписк)|стоит|бесплат|подписк|тариф|платн)/.test(t))
    return `14 дней — всё бесплатно, потом 3 сметы в месяц тоже бесплатно. «Лайт» (сметы без ограничений, ваш логотип) — ${PRICES.lite} ₽/мес, первый месяц ${PRICES.liteFirst} ₽. «Про» (плюс договоры, акты, учёт денег) — ${PRICES.pro} ₽, первый месяц ${PRICES.proFirst} ₽. Без автосписаний. Всё в Telegram: ${BOT} 👷`;
  if (/(айфон|iphone|андроид|android|скача|установ|компьютер|пк\b|ноутбук)/.test(t))
    return `Ничего скачивать не нужно — это Telegram-бот ${BOT}, работает на любом телефоне и на компьютере 👍`;
  if (/(где|ссылк|как найти|название|что за (прил|бот|програм)|прилож|как называ)/.test(t))
    return `Это Telegram-бот ${BOT} — открывается прямо в Telegram 👍`;
  if (/(3d|3д|визуализ|чертеж|модел|как будет выгляд)/.test(t))
    return `3D-конструктор и смета по модели — бесплатно в ${BOT}. Готовый 3D-проект для заказчика — первый ${PRICES.designFirst} ₽, дальше ${PRICES.design} ₽ за объект.`;
  if (/(материал|петрович|леруа|цены (на )?материал|актуальн|регион|город|москв|спб|питер)/.test(t))
    return `Цены работ и материалов можно ставить свои — бот их запомнит. Есть база материалов с ценами (сейчас СПб), список растёт. Попробуйте: ${BOT}`;
  if (/(договор|акт|pdf|пдф|заказчик|отправ|печат)/.test(t))
    return `Смета уходит заказчику в PDF, договор и акты — тоже из бота. Попробуйте: ${BOT} 📄`;
  if (/(бригад|команд|несколько (человек|мастер)|прораб)/.test(t))
    return `Для бригады есть общий справочник цен и доступ для мастеров. Начать можно бесплатно: ${BOT}`;
  if (/(как работа|как пользова|научит|сложно|разобрат|инструкц)/.test(t))
    return `Всё просто: выбираете работы — бот считает объёмы, материалы и итог, смета готова за пару минут. Попробуйте бесплатно: ${BOT}`;
  if (/(можно ли|а можно|умеет|есть ли|а есть|поддерживает|работает ли)/.test(t)) return null; // конкретный вопрос — владелице
  return null;
}

/** Вежливый общий ответ, если владелица не ответила сама */
export function fallbackReply(seed: string) {
  return pick(seed, [
    `Спасибо за комментарий! Всё можно посмотреть и попробовать бесплатно в ${BOT} 🙌`,
    `Спасибо! Если есть вопрос по сметам — загляните в ${BOT}, там всё под рукой 👷`,
    `Благодарим за отклик! Попробуйте сами — 14 дней бесплатно: ${BOT}`,
  ]);
}
