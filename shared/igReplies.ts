/** Instagram: готовые ответы на частые комментарии (остальные пересылаются владелице в бот) */
const BOT = '@CMETA_Pro_bot';
/** Готовые ответы на частые вопросы; null — переслать администратору */
export function autoReply(text: string): string | null {
  const t = text.toLowerCase();
  if (/(сколько|цен[аы]|стоит|бесплат|подписк|тариф|руб)/.test(t)) return `Бесплатно — 3 сметы в месяц. «Про» — 490 ₽/мес, первый месяц 200 ₽. Всё прямо в Telegram: ${BOT} 👷`;
  if (/(где|ссылк|скач|как найти|название|что за (прил|бот)|прилож)/.test(t)) return `Это Telegram-бот ${BOT} — открывается прямо в Telegram, ничего скачивать не нужно 👍`;
  if (/(3d|3д|проект|чертеж|чертёж)/.test(t)) return `3D-конструктор и смета по модели — бесплатно в ${BOT}. Готовый 3D-проект для заказчика — 490 ₽ за объект.`;
  if (/^[\s!.]*(круто|класс|огонь|топ|супер|кайф|ахах|хаха|лол|😂|🔥|👍|❤️|😍|👏)+[\s!.)]*$/u.test(t)) return 'Спасибо! 🙌';
  return null;
}

